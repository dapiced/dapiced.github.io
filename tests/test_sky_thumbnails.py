"""Every APOD image has the lightweight grid thumbnail that /sky/ and the
homepage "Sky of the day" card display (generated by Cosmic Daily)."""
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
APOD_IMAGES = ROOT / "assets" / "img" / "apod"


def test_every_apod_image_has_a_thumbnail():
    missing = [
        image.name
        for image in sorted(APOD_IMAGES.glob("*.webp"))
        if not (APOD_IMAGES / "thumbs" / image.name).is_file()
    ]
    assert not missing, (
        "Missing /sky/ thumbnails (run `python -m cosmic_daily thumbnails` "
        f"in tools/cosmic-daily): {', '.join(missing)}"
    )


def test_thumbnails_are_at_most_640_px_wide():
    for thumbnail in APOD_IMAGES.glob("thumbs/*.webp"):
        with Image.open(thumbnail) as image:
            assert image.width <= 640, thumbnail.name


def test_sky_templates_use_the_thumbnails():
    for template in (ROOT / "sky" / "index.html", ROOT / "_includes" / "sky-today.html"):
        source = template.read_text(encoding="utf-8")
        assert '"/assets/img/apod/thumbs/"' in source, template.name
